export const EASE = [0.22, 0.9, 0.24, 1] as const

const ROMAN: [number, string][] = [
  [10, 'X'],
  [9, 'IX'],
  [5, 'V'],
  [4, 'IV'],
  [1, 'I'],
]
export function roman(n: number): string {
  let out = ''
  for (const [v, s] of ROMAN) while (n >= v) ((out += s), (n -= v))
  return out || String(n)
}

/** Glass panel with an eyebrow label and a serif title. */
export function Panel({
  eyebrow,
  title,
  icon,
  right,
  children,
  className = '',
  bodyClass = '',
}: {
  eyebrow?: ReactNode
  title?: ReactNode
  icon?: ReactNode
  right?: ReactNode
  children: ReactNode
  className?: string
  bodyClass?: string
}) {
  return (
    <section className={`panel rise flex min-w-0 flex-col ${className}`}>
      {(title != null || eyebrow != null) && (
        <header className="panel-head">
          {icon && <span className="grid h-7 w-7 shrink-0 place-items-center rounded-full border border-gold/25 bg-gold/[0.06] text-gold">{icon}</span>}
          <div className="min-w-0 leading-tight">
            {eyebrow != null && <div className="eyebrow">{eyebrow}</div>}
            {title != null && <div className="title-serif truncate text-[19px]">{title}</div>}
          </div>
          <div className="ml-auto flex shrink-0 items-center gap-2">{right}</div>
        </header>
      )}
      <div className={`min-h-0 flex-1 ${bodyClass}`}>{children}</div>
    </section>
  )
}

