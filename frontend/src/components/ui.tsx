export function LlmBadge({ llm }: { llm?: LlmSource | string | null }) {
  if (!llm || llm === 'none') return null
  if (llm === 'gemini')
    return (
      <Chip className="border-info/35 bg-info/10 text-info" title="Generated by Gemini">
        <span className="h-1 w-1 rounded-full bg-info" /> Gemini
      </Chip>
    )
  if (llm === 'mixed')
    return (
      <Chip className="border-warn/35 bg-warn/10 text-warn" title="Some calls fell back to the offline engine">
        Mixed
      </Chip>
    )
  return (
    <Chip className="border-gold/30 bg-gold/[0.07] text-gold" title="Rule-based offline engine (no LLM)">
      Offline engine
    </Chip>
  )
}

export function Bar({ value, max, color }: { value: number; max: number; color: string }) {
  const w = max > 0 ? Math.max(0, Math.min(100, (value / max) * 100)) : 0
  return (
    <div className="h-[6px] w-full overflow-hidden rounded-full bg-ink-700/80">
      <div
        className="grow-x h-full rounded-full transition-[width] duration-700"
        style={{ width: `${w}%`, background: `linear-gradient(90deg, color-mix(in srgb, ${color} 55%, transparent), ${color})`, boxShadow: `0 0 12px -2px ${color}` }}
      />
    </div>
  )
}

