/** Number that glides to its new value. */
export function AnimatedNumber({ value, format, className = '' }: { value: number | null | undefined; format: (n: number) => string; className?: string }) {
  const mv = useMotionValue(value ?? 0)
  const [text, setText] = useState(() => (value == null ? '—' : format(value)))
  const fmt = useRef(format)
  fmt.current = format
  useEffect(() => {
    if (value == null) {
      setText('—')
      return
    }
    const controls = animate(mv, value, { duration: 0.9, ease: EASE, onUpdate: (v) => setText(fmt.current(v)) })
    return () => controls.stop()
  }, [value, mv])
  return <span className={className}>{text}</span>
}

/** Wraps a control so it leans slightly toward the cursor. */
export function Magnetic({ children, strength = 0.22 }: { children: ReactNode; strength?: number }) {
  const ref = useRef<HTMLDivElement>(null)
  const x = useSpring(0, { stiffness: 220, damping: 18, mass: 0.4 })
  const y = useSpring(0, { stiffness: 220, damping: 18, mass: 0.4 })
  const onMove = (e: MouseEvent) => {
    const r = ref.current?.getBoundingClientRect()
    if (!r) return
    x.set((e.clientX - (r.left + r.width / 2)) * strength)
    y.set((e.clientY - (r.top + r.height / 2)) * strength)
  }
  const reset = () => {
    x.set(0)
    y.set(0)
  }
  return (
    <motion.div ref={ref} onMouseMove={onMove} onMouseLeave={reset} style={{ x, y }} className="inline-flex">
      {children}
    </motion.div>
  )
}

export function RoyalButton({ children, className = '', ...rest }: ButtonHTMLAttributes<HTMLButtonElement>) {
  return (
    <Magnetic>
      <button {...rest} className={`btn-royal ${className}`}>
        {children}
      </button>
    </Magnetic>
  )
}

/** Tracks the cursor for the `.spotlight` hover glow. */
export function useSpotlight() {
  return (e: MouseEvent<HTMLElement>) => {
    const r = e.currentTarget.getBoundingClientRect()
    e.currentTarget.style.setProperty('--mx', `${e.clientX - r.left}px`)
    e.currentTarget.style.setProperty('--my', `${e.clientY - r.top}px`)
  }
}
