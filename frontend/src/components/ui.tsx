import type { ReactNode } from 'react'
import type { LlmSource } from '../types'

export function Panel({
  title,
  icon,
  right,
  children,
  className = '',
  bodyClass = '',
}: {
  title?: ReactNode
  icon?: ReactNode
  right?: ReactNode
  children: ReactNode
  className?: string
  bodyClass?: string
}) {
  return (
    <section className={`panel flex min-w-0 flex-col ${className}`}>
      {title != null && (
        <header className="panel-head">
          {icon}
          <span className="truncate">{title}</span>
          <div className="ml-auto flex items-center gap-2 normal-case tracking-normal">{right}</div>
        </header>
      )}
      <div className={`min-h-0 flex-1 ${bodyClass}`}>{children}</div>
    </section>
  )
}

export function Stat({ label, value, sub, valueClass = '' }: { label: string; value: ReactNode; sub?: ReactNode; valueClass?: string }) {
  return (
    <div className="min-w-0">
      <div className="label">{label}</div>
      <div className={`tabular mt-0.5 truncate text-[15px] font-medium text-fg ${valueClass}`}>{value}</div>
      {sub != null && <div className="tabular truncate text-[11px] text-muted">{sub}</div>}
    </div>
  )
}

export function Chip({ children, className = '', title }: { children: ReactNode; className?: string; title?: string }) {
  return (
    <span
      title={title}
      className={`inline-flex items-center gap-1 rounded border px-1.5 py-px font-mono text-[10px] leading-4 tracking-wide uppercase ${className}`}
    >
      {children}
    </span>
  )
}

export function LlmBadge({ llm }: { llm?: LlmSource | string | null }) {
  if (!llm || llm === 'none') return null
  return llm === 'gemini' ? (
    <Chip className="border-info/40 bg-info/10 text-info" title="Generated by Gemini">
      Gemini
    </Chip>
  ) : llm === 'mixed' ? (
    <Chip className="border-warn/40 bg-warn/10 text-warn" title="Some calls fell back to the offline engine">
      Mixed
    </Chip>
  ) : (
    <Chip className="border-amber/40 bg-amber/10 text-amber" title="Rule-based offline engine (no LLM)">
      Offline engine
    </Chip>
  )
}

export function Bar({ value, max, color }: { value: number; max: number; color: string }) {
  const w = max > 0 ? Math.max(0, Math.min(100, (value / max) * 100)) : 0
  return (
    <div className="h-1.5 w-full overflow-hidden rounded-full bg-ink-700">
      <div className="h-full rounded-full transition-[width] duration-700" style={{ width: `${w}%`, background: color }} />
    </div>
  )
}

export function Empty({ children }: { children: ReactNode }) {
  return <div className="flex h-full min-h-[80px] items-center justify-center px-4 text-center text-[12px] text-dim">{children}</div>
}
